"""Worker Loop persistente (P0-4)."""
import time
import uuid
from datetime import datetime, timezone
from api import task_bus

def process_task(task: dict) -> dict:
    task_id = task["task_id"]
    task_bus.mark_task_running(task_id)
    time.sleep(1) 
    candidate_result = {
        "candidate_id": str(uuid.uuid4()),
        "worker_id": "worker-agent-01",
        "status": "candidate",
        "summary": f"Processed objective: {task.get('objective', 'unknown')}",
        "evidence": [{"evidence_id": str(uuid.uuid4()), "kind": "calculation", "source": "real_worker", "observed_at": datetime.now(timezone.utc).isoformat(), "description": "Auto-generated by persistent worker."}],
        "assumptions": [], "contradictions": [], "trace_id": task.get("trace_id")
    }
    task_bus.mark_task_completed(task_id, candidate_result)
    return candidate_result

def main():
    print("Worker persistente iniciado. Escuchando el Task Bus...")
    while True:
        task = task_bus.get_next_task()
        if task:
            process_task(task)
        time.sleep(2)

if __name__ == "__main__":
    main()
